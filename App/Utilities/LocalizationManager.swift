import SwiftUI
import Combine

/// Code-based localization manager for Simastry.
/// Supports runtime language switching without restart.
@MainActor
final class LocalizationManager: ObservableObject {
    static let shared = LocalizationManager()

    enum Language: String, CaseIterable, Identifiable {
        case english = "en"
        case spanish = "es"
        case portuguese = "pt-BR"
        case french = "fr"
        case german = "de"
        case russian = "ru"
        case turkish = "tr"
        case thai = "th"

        var id: String { rawValue }

        var displayName: String {
            switch self {
            case .english: "English"
            case .spanish: "Español"
            case .portuguese: "Português"
            case .french: "Français"
            case .german: "Deutsch"
            case .russian: "Русский"
            case .turkish: "Türkçe"
            case .thai: "ไทย"
            }
        }

        var shortCode: String {
            switch self {
            case .english: "EN"
            case .spanish: "ES"
            case .portuguese: "PT"
            case .french: "FR"
            case .german: "DE"
            case .russian: "RU"
            case .turkish: "TR"
            case .thai: "TH"
            }
        }
    }

    @Published var currentLanguage: Language {
        didSet {
            UserDefaults.standard.set(currentLanguage.rawValue, forKey: "appLanguage")
        }
    }

    private init() {
        let saved = UserDefaults.standard.string(forKey: "appLanguage") ?? "en"
        currentLanguage = Language(rawValue: saved) ?? .english
    }

    /// Get localized string.
    func string(_ key: String) -> String {
        LocalizedStrings.strings[currentLanguage.rawValue]?[key]
            ?? LocalizedStrings.strings["en"]?[key]
            ?? key
    }

    func string(_ key: String, replacements: [String: String]) -> String {
        replacements.reduce(string(key)) { partial, replacement in
            partial.replacingOccurrences(of: "%{\(replacement.key)}", with: replacement.value)
        }
    }

    func list(_ key: String) -> [String] {
        string(key)
            .split(separator: "|")
            .map { String($0).trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty }
    }
}

